def _write_repo(root, manifest=MANIFEST, lock=LOCK, one=ONE, two=TWO):
    root = Path(root)
    (root / "Cargo.toml").write_text(manifest)
    (root / "Cargo.lock").write_text(lock)
    (root / "crates" / "one").mkdir(parents=True)
    (root / "crates" / "two").mkdir(parents=True)
    (root / "crates" / "one" / "Cargo.toml").write_text(one)
    (root / "crates" / "two" / "Cargo.toml").write_text(two)
    return root


def _snapshot(root):
    rows = []
    for rel in TRACKED:
        path = root / rel
        rows.append((path.read_bytes(), path.stat().st_mtime_ns))
    return rows


