def _rewrite_release_json(archive, version):
    with tarfile.open(archive, "r:gz") as src:
        members = src.getmembers()
        payloads = {}
        for member in members:
            extracted = src.extractfile(member)
            payloads[member.name] = b"" if extracted is None else extracted.read()
    payload = json.loads(payloads["release.json"])
    payload["version"] = version
    payloads["release.json"] = json.dumps(payload).encode()
    with tarfile.open(archive, "w:gz") as dst:
        for member in members:
            data = payloads[member.name]
            info = tarfile.TarInfo(member.name)
            info.size = len(data)
            info.mode = member.mode
            info.mtime = 0
            dst.addfile(info, io.BytesIO(data))


